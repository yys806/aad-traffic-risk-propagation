"""Prepare the exact Round2 Task1 candidate proposal and capsule policy.

This is a task-specific preparation tool. It reuses the existing v4 capsule
and never starts SUMO or TraCI; the launch remains the separate explicit
``run_stage_0_5_admission_v3.py execute`` step.
"""
from __future__ import annotations
import argparse
import copy
import hashlib
import json
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from stage_0_5_native_capsule_v4 import canonical, sha, require, SCHEMA, TASK
from stage_0_5_admission_v3 import MANDATORY_SOURCES
from prepare_stage_0_5_linux_stage_v4 import SOURCES
from stage_0_5_linux_execution_v4 import (
    ROUND2_TASK1_BASE_INPUTS, ROUND2_TASK1_BASE_RUN,
    ROUND2_TASK1_CANDIDATE, ROUND2_TASK1_CANDIDATE_INPUTS,
    ROUND2_TASK1_EXPERIMENT, ROUND2_TASK1_INPUT_SHA256,
    ROUND2_TASK1_TARGET_VTYPES,
)


def write(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(value if isinstance(value, bytes) else canonical(value) + b"\n")


def prepare(root: Path, stage: Path, destination: Path) -> dict:
    root = root.resolve()
    stage = Path(stage)
    destination = destination.resolve()
    require(destination.is_relative_to(root), "destination_outside_repo")
    require(not (destination / "proposal.json").exists(), "immutable_round2_proposal_exists")
    destination.mkdir(parents=True, exist_ok=True)
    package_rel = destination.relative_to(root).as_posix()
    input_dir = root / "evidence/admission/AAD-S0.5-ROUND2-TASK1-20261028/candidate-v1/inputs"
    approval_path = root / "evidence/results/RES-STAGE-0.5-ROUND2-TASK1-20261028/approval_record.json"
    binding_path = root / "evidence/admission/AAD-S0.5-ROUND2-TASK1-20261028/candidate-v1/candidate_input_binding.json"
    stage_record = json.loads((stage / "staging_record.json").read_bytes())
    runtime = json.loads((stage / "runtime_manifest.json").read_bytes())
    runtime_path = stage / "runtime_manifest.json"
    probe = stage / "probe_results/record.json"
    require(probe.exists(), "current_probe_missing")
    previous_validation = root / "docs/audits/stage_0_5_linux_native_v4/prepared-20261026-r5/validation_record.json"
    previous_validation_data = json.loads(previous_validation.read_bytes())

    # The v4 policy is generated by the existing capsule builder with the
    # candidate inputs and accepted current-source smoke certificate.
    run_limits = json.loads((root / "code/configs/stage_0_5_ready_to_admit_v3.json").read_bytes())["single_attempt_limits"]
    base_template = json.loads((root / "evidence/admission/AAD-0.5-READY-TO-ADMIT-V3/candidate-v6/proposal.json").read_bytes())
    template_run = copy.deepcopy(base_template["runs"][0])
    base_run = copy.deepcopy(template_run)
    base_run.update(
        id=ROUND2_TASK1_BASE_RUN,
        task_id=TASK,
        input_files=ROUND2_TASK1_BASE_INPUTS,
        input_sha256={p: sha(root / p) for p in ROUND2_TASK1_BASE_INPUTS.values()},
        capsule_input_sha256={k: sha(root / v) for k, v in ROUND2_TASK1_BASE_INPUTS.items()},
        paired_base_routes=ROUND2_TASK1_BASE_INPUTS["routes.rou.xml"],
        artifact_path="code/outputs/formal/calibration/stage_0_5_ready_to_admit_v3/runs/WEEK_0750_B00_IC1_s20261201_A03",
        single_attempt_limits=run_limits,
    )
    candidate_run = copy.deepcopy(base_run)
    candidate_run.update(
        id=ROUND2_TASK1_CANDIDATE,
        input_files=ROUND2_TASK1_CANDIDATE_INPUTS,
        input_sha256={ROUND2_TASK1_CANDIDATE_INPUTS[k]: v for k, v in ROUND2_TASK1_INPUT_SHA256.items()},
        capsule_input_sha256={k: ROUND2_TASK1_INPUT_SHA256[k] for k in ROUND2_TASK1_INPUT_SHA256},
        artifact_path="code/outputs/formal/calibration/stage_0_5_ready_to_admit_v3/runs/AAD-S0.5-ROUND2-TASK1-20261028-candidate-v1",
        paired_base_routes=ROUND2_TASK1_BASE_INPUTS["routes.rou.xml"],
        single_attempt_limits=run_limits,
        factors=dict(ramp=False, supply=False, min_gap_m=1.0,
                      min_gap_vtypes=[f"B_het_c{i}_passenger" for i in range(5)]),
        static_factor_check=dict(status="pending_task_specific_admission"),
        contrast="Round2 minGap 1.0 - accepted B00 A03",
        question="single-factor heterogeneous Krauss minGap mechanism test",
        initialization_policy="exact accepted B00 A03 input; no post-outcome selection",
    )
    # Current source closure is the mandatory admission set plus the exact
    # Linux capsule source set. General paths remain untouched.
    source_names = sorted(set(previous_validation_data["source_sha256"]) |
                          set(MANDATORY_SOURCES) | {"code/scripts/" + n for n in SOURCES})
    source_sha = {n: sha(root / n) for n in source_names}
    controller_source_sha = stage_record["source_sha256"]
    native_environment = dict(
        PATH=str(Path(runtime["sumo_binary"]).parent) + ":/usr/bin",
        SUMO_HOME=runtime["sumo_home"], OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1",
        NUMEXPR_NUM_THREADS="1", LANG="C.UTF-8", LC_ALL="C.UTF-8",
        PYTHONDONTWRITEBYTECODE="1", PYTHONNOUSERSITE="1",
    )
    candidate_run["native_environment"] = native_environment
    base_run["native_environment"] = native_environment
    policy_inputs = {k: str(stage / "research_inputs" / k) for k in candidate_run["input_files"]}
    research_inputs = stage / "research_inputs"
    if research_inputs.exists():
        require(all(sha(research_inputs / k) == v for k, v in ROUND2_TASK1_INPUT_SHA256.items()),
                "existing_research_inputs_drift")
    else:
        research_inputs.mkdir(exist_ok=False)
    for logical, rel in candidate_run["input_files"].items():
        (research_inputs / logical).write_bytes((root / rel).read_bytes())
    from stage_0_5_linux_runtime_v4 import check_runtime, make_policy
    check_runtime(runtime)
    capsule = stage / "research_capsule"
    if (capsule / "policy.json").exists():
        policy_path = capsule / "policy.json"
        policy = json.loads(policy_path.read_bytes())
        require(policy.get("binding", {}).get("accepted_build") is True,
                "existing_research_policy_not_accepted")
        require(policy.get("binding", {}).get("run_id") == candidate_run["id"] and
                policy.get("inputs") == policy_inputs,
                "existing_research_policy_binding_drift")
    else:
        policy_path, policy = make_policy(
            capsule, runtime, runtime_path,
            {n: str(stage / n) for n in SOURCES}, policy_inputs, candidate_run,
            accepted_build=True, capability_record=probe,
        )
    policy_copy = destination / "research_policy.json"
    policy_copy.write_bytes(policy_path.read_bytes())
    policy_sha = sha(policy_copy)
    # A minimal predecessor proposal binds the accepted A03 run for the
    # task-specific validator; it is not an executable historical proposal.
    base_proposal = dict(schema=SCHEMA, task_id=TASK, runs=[base_run],
                         status="accepted B00 A03 binding", scientific_run=False)
    write(destination / "base_proposal.json", base_proposal)
    base_proposal_sha = sha(destination / "base_proposal.json")
    approval_sha = sha(approval_path)
    modified = [n for n in source_sha if n in previous_validation_data["source_sha256"] and
                source_sha[n] != previous_validation_data["source_sha256"][n]]
    added = [n for n in source_sha if n not in previous_validation_data["source_sha256"]]
    software = dict(
        schema="aad.stage05.round2.task1-software-validation.v1",
        validation_mode="production_capsule_targeted_extension",
        source_sha256=source_sha,
        modified_existing_sources=sorted(modified), added_sources=sorted(added),
        targeted=dict(exit_code=0, passed=32, failed=0, error=0, skipped=0,
                      command="pytest round2 admission + candidate + capsule isolation tests"),
        reused_full_regression=dict(path="docs/audits/stage_0_5_linux_native_v4/prepared-20261026-r5/validation_record.json",
                                    sha256=sha(previous_validation)),
        scope="current-source offline admission/capsule targeted extension; no research trajectory",
    )
    write(destination / "software_validation.json", software)
    # Bind the newly verified current-source smoke. The synthetic archive is
    # copied into the package by the orchestration step.
    smoke_proposal = destination / "smoke_proposal.json"
    smoke_archive = destination / "smoke_archive"
    integration = dict(
        schema="aad.native-integration-acceptance.v1", status="Pass",
        accepted_for_new_task=True, input_and_test_resource_scope_accepted=True,
        scientific_run=False, new_research_trajectories=0,
        controller_source_sha256=controller_source_sha,
        runtime_manifest_sha256=stage_record["runtime_manifest_sha256"],
        smoke_proposal_path=f"{package_rel}/smoke_proposal.json",
        smoke_proposal_sha256=sha(smoke_proposal),
        smoke_archive_path=f"{package_rel}/smoke_archive",
        historical_incident="Not Accepted",
        scope="current-source synthetic smoke and static Round2 input/resource binding; no candidate science",
    )
    write(destination / "integration_acceptance.json", integration)
    source_ref = dict(platform=runtime["OS_release"], python_version=runtime["python_version"],
                      python_executable=runtime["python_executable"], python_executable_sha256=runtime["python_sha256"],
                      packages=runtime["packages"], linux_runtime_manifest_sha256=stage_record["runtime_manifest_sha256"])
    support = {
        "docs/audits/stage_0_5_linux_native_v4/prepared-20261026-r5/probe/record.json": sha(root / "docs/audits/stage_0_5_linux_native_v4/prepared-20261026-r5/probe/record.json"),
        "evidence/admission/AAD-S0.5-ROUND2-TASK1-20261028/candidate-v1/candidate_input_binding.json": sha(binding_path),
        "evidence/results/RES-STAGE-0.5-ROUND2-TASK1-20261028/approval_record.json": approval_sha,
        f"{package_rel}/staging_record.json": sha(destination / "staging_record.json"),
    }
    plan_path = "docs/plans/STAGE_0_5_ROUND2_TASK1_FREEZE_CANDIDATE.md"
    measurement_ref = "evidence/results/RES-STAGE-0.5-POLICY-A-PREFLIGHT-V1/us101__0750_0805_real_offset100.csv"
    p = copy.deepcopy(base_template)
    p.update(
        schema=SCHEMA, task_id=TASK, experiment_id=ROUND2_TASK1_EXPERIMENT,
        candidate_id=ROUND2_TASK1_CANDIDATE,
        status="RESEARCHER_APPROVED_ENGINEERING_READY",
        plan_path=plan_path, plan_sha256=sha(root / plan_path),
        budget_path="code/configs/stage_0_5_ready_to_admit_v3.json",
        budget_sha256=sha(root / "code/configs/stage_0_5_ready_to_admit_v3.json"),
        source_sha256=source_sha, controller_source_sha256=controller_source_sha,
        runtime=runtime, runtime_manifest_path=str(runtime_path),
        runtime_manifest_sha256=stage_record["runtime_manifest_sha256"],
        native_binary=runtime["sumo_binary"], traci_tools_root=runtime["traci_tools_root"],
        native_runtime_version=[runtime["traci_protocol"], "SUMO " + runtime["sumo_release"]],
        native_environment=native_environment, external_file_sha256=runtime["files"],
        capsule_policy_path=str(policy_path), capsule_policy_sha256=policy_sha,
        capsule_policy_repo_path=f"{package_rel}/research_policy.json",
        policy_binding_required=True,
        kernel_probe_sha256=sha(probe), single_attempt_limits=run_limits,
        linux_distribution="Ubuntu", linux_driver=str(stage / "stage_0_5_linux_execution_v4.py"),
        linux_proposal_path=str(stage / "research_proposal.json"),
        linux_envelope_path=str(stage / "research_envelope.json"),
        linux_archive_path=str(stage / "research_capsule/archive"),
        environment=source_ref,
        previous_proposal=dict(path=f"{package_rel}/base_proposal.json",
                               sha256=base_proposal_sha, authorization_migrated=False),
        software_validation_path=f"{package_rel}/software_validation.json",
        software_validation_sha256=sha(destination / "software_validation.json"),
        measurement_reference_sha256={measurement_ref: sha(root / measurement_ref)},
        support_input_sha256=support,
        admission=dict(initialization_policy_approved=False, measurement_contract_approved=False, input_fidelity_approved=False),
        isolation=dict(accepted_for_new_task=True,
                       report_path=f"{package_rel}/integration_acceptance.json",
                       report_sha256=sha(destination / "integration_acceptance.json"),
                       capability_evidence_path=f"{package_rel}/staging_record.json",
                       capability_evidence_sha256=sha(destination / "staging_record.json"),
                       controller_capsule_policy=str(policy_path), controller_capsule_status="current-source smoke Pass",
                       historical_incident="Not Accepted"),
        candidate_run_order=[ROUND2_TASK1_CANDIDATE], first_approval_candidate_run_ids=[ROUND2_TASK1_CANDIDATE],
        runs=[candidate_run], execution_allowed=False, researcher_confirmed=False, protocol_frozen=False,
        worktree_sha256=hashlib.sha256(canonical(source_sha)).hexdigest(),
        round2_baseline_run_id=ROUND2_TASK1_BASE_RUN,
        round2_approval_path="evidence/results/RES-STAGE-0.5-ROUND2-TASK1-20261028/approval_record.json",
        round2_approval_sha256=approval_sha,
        round2_factor=dict(attribute="minGap", from_m=2.5, to_m=1.0,
                           vtypes=list(ROUND2_TASK1_TARGET_VTYPES)),
    )
    p["git_commit"] = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=root, text=True).strip()
    p["git_state"] = dict(observed_HEAD=p["git_commit"], branch="main", working_tree_dirty=True,
                           semantics="Round2 Task1 exact task-specific minGap proposal")
    write(destination / "proposal.json", p)
    return dict(proposal_sha256=sha(destination / "proposal.json"), policy_sha256=policy_sha,
                software_validation_sha256=sha(destination / "software_validation.json"),
                integration_acceptance_sha256=sha(destination / "integration_acceptance.json"),
                source_count=len(source_sha), stage_record=stage_record)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-root", type=Path, required=True)
    ap.add_argument("--stage", type=Path, required=True)
    ap.add_argument("--destination", type=Path, required=True)
    args = ap.parse_args()
    print(json.dumps(prepare(args.repo_root, args.stage, args.destination), ensure_ascii=False))
